// mds build-kit: templates/<type>.md, kit/skills/mdstandard/types/<type>.md, kit/skills/mdstandard/links.md.
import path from 'node:path';
import { STANDARD_DIR } from './schema.mjs';
import { writeIfChanged, toPosix } from './util.mjs';
import { renderCard } from './templates.mjs';

const GEN_NOTE = '> Generated by `mds build-kit` from `schema.json` — do not edit by hand.';
const code = (s) => '`' + s + '`';
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

function valuesText(S, def, type) {
  if (def.values === '@statusVocabulary') return 'status vocabulary below, or `—`';
  if (def.values === '@typeRoster') return code(type);
  const vn = S.vocabName(def.values);
  if (vn) return `a value of ### ${vn} in project.md` + (S.reserved[vn] ? ` (or ${code(S.reserved[vn])})` : '');
  if (Array.isArray(def.values)) return def.values.map(code).join(' · ');
  if (def.value) return code(def.value);
  if (def.pattern) return `pattern ${code(def.pattern)}`;
  return '';
}

function keyRows(S, type) {
  const t = S.typeDef(type);
  const rows = [];
  for (const raw of t.keys) {
    const key = raw.replace(/\?$/, '');
    const req = raw.endsWith('?') ? 'no' : 'yes';
    if (key === 'x-*') { rows.push([code('x-*'), 'no', 'extension keys; kept untouched, always last']); continue; }
    const def = S.keyDef(type, key) || {};
    let text;
    if (key === 'standard') text = code(S.standard) + ' — always the first key';
    else if (key === 'type') text = code(type);
    else if (key === 'status') text = 'status vocabulary below, or `—`';
    else if (key === 'state') text = 'a State of project.md (one value' + (['userflow', 'ia'].includes(type) ? '' : ' or a list') + '); omitted = Shared; only when States are declared';
    else if (key === 'feature') text = 'FT core of this card\'s home Feature or Sub-feature (one)';
    else if (key === 'id') text = `${code(t.prefix + '000000')}-style core (${t.prefix} + 6 digits) — minted by ${code('mds new')}, never by hand`;
    else if (key === 'name') text = 'the card name (no `[` `]`); title, references and filename slug derive from it';
    else if (key === 'origin') text = `${code('<kb>/<core>')} — written by import`;
    else {
      text = valuesText(S, def, type);
      const extra = def.description || def.rule || '';
      if (extra) text = text ? `${text} — ${extra}` : extra;
      if (S.alwaysQuoted.has(key)) text += ' (always quoted)';
    }
    rows.push([code(key), req, text]);
  }
  return rows;
}

function relationRows(S, type) {
  const rows = [];
  const kindLabel = { 'screen-variant': '### variant (#SV)', 'component-variant': '### variant (#CV)', 'shell-variant': '### variant (#HV)', 'flow-step': '### step (#FS)', 'flow-variant': '## Step list › ### flow variant' };
  for (const [name, r] of Object.entries(S.relations)) {
    if (r.generatedOnly) continue;
    const where = [];
    for (const a of r.authoredIn || []) {
      if (a.key && a.type === type) where.push(`front matter ${code(a.key + ':')}`);
      else if (a.passportKey) { if (S.raw.subdocuments[a.subdocument]?.host === type) where.push(`${kindLabel[a.subdocument]} passport ${code(a.passportKey + ':')}`); }
      else if (a.relation) { if ((a.relation === 'Node' && type === 'ia') || (a.relation === 'Screen' && type === 'userflow')) where.push(`${code('· ' + a.qualifier + ':')} on ${a.relation}`); }
      else if (a.section && a.type === type) where.push(`## ${a.section}${a.subsection ? ' › ### ' + a.subsection : ''}${a.prefixless ? ' (no prefix)' : ''}`);
      else if (a.subdocument && (S.hostOfKind(a.subdocument) === type || S.raw.subdocuments[a.subdocument]?.host === type)) {
        where.push(kindLabel[a.subdocument] + (a.shapes ? ` ${a.shapes.join('/')}` : '') + (a.prefixless ? ' (no prefix)' : ''));
      }
    }
    if (!where.length) continue;
    const targets = r.textSlot ? 'text' : r.targetTypes.length ? r.targetTypes.join(', ') : (r.target || '—');
    const quals = (r.qualifiers || []).map((q) => (q.valueless ? q.key : `${q.key}: ${Array.isArray(q.values) ? q.values.join('|') : q.values ? q.values.replace('@vocabulary:', '') : '…'}`)).join(' · ') || '—';
    const gr = r.generatedReverse;
    const rev = gr ? (Array.isArray(gr.section) ? gr.section.join(', ') : gr.section) + ` on ${gr.on.join(', ')}` : '—';
    rows.push([name, cell(where.join('; ')), cell(targets), cell(quals), cell(rev)]);
  }
  return rows;
}

function table(head, rows) {
  return [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)];
}

function presetBlock(S, type) {
  const rp = S.raw.requirementPresets;
  const def = rp.defaults[type] || (type === 'userflow' ? rp.defaults['flow-step'] : null);
  const out = ['## Requirement blocks', '', `${rp.where} Marker ${code(rp.marker)}: ${rp.numbering}${def ? ` Default preset here: **${def}** (${rp.defaultsNote.toLowerCase()})` : ''}`, '', '```markdown'];
  let n = 0;
  const blocks = [];
  for (const [name, p] of Object.entries(rp.presets)) {
    const marker = `**R${++n} · ${name}**`;
    const shape = p.shape.split(' / ');
    blocks.push(/^On the marker line/.test(p.placement) ? [`${marker} ${shape.join(' ')}`] : [marker, ...shape]);
  }
  blocks.forEach((b, i) => out.push(...(i ? [''] : []), ...b));
  out.push('```', '', Object.entries(rp.presets).map(([name, p]) => `**${name}**: ${p.rule}`).join(' · ') + ` ${rp.slotUnknown}`, '');
  return out;
}

export function overviewSheet(S) {
  const out = ['# Card types — overview', '', GEN_NOTE, '', 'The modelling cheat sheet: pick the type by its purpose, then check what it is not. Details per type: `types/<type>.md`.', ''];
  for (const t of S.roster) {
    const d = S.typeDef(t);
    out.push(`**${t}** · ${d.prefix} · ${d.folder ? code(d.folder + '/') : code(d.file)} — ${d.purpose}`);
    for (const n of d.notToConfuseWith || []) out.push(`- not ${n.type}: ${n.rule}`);
    out.push('');
  }
  const subs = Object.entries(S.raw.subdocuments).filter(([, v]) => v.prefix).map(([k, v]) => `${k} (${v.prefix}, a \`### \` sub-document in ## ${v.section} of a ${v.host})`);
  out.push(`Sub-documents have their own core but no file: ${subs.join(' · ')}.`);
  return out.join('\n') + '\n';
}

export function typeSheet(S, type) {
  const t = S.typeDef(type);
  const out = [`# ${type} · ${t.prefix}${t.folder ? ` · folder ${code(t.folder + '/')}` : ` · ${code(t.file)}`}`, '', GEN_NOTE, '', t.purpose, ''];
  out.push(`**When to use.** ${t.whenToUse}`, '');
  if (t.notToConfuseWith?.length) {
    out.push('**Not to confuse with**');
    for (const n of t.notToConfuseWith) out.push(`- **${n.type}** — ${n.rule}`);
    out.push('');
  }
  if (t.modelling?.length) out.push('**How to model**', ...t.modelling.map((l) => `- ${l}`), '');
  if (t.levels) out.push(`**Levels.** Feature: ${t.levels.feature} Sub-feature: ${t.levels.subfeature}`, '');
  if (t.altitude) out.push(`**Altitude.** ${typeof t.altitude === 'string' ? t.altitude : `Feature: ${t.altitude.feature} Sub-feature: ${t.altitude.subfeature}`}`, '');
  out.push('## Front matter', '', ...table(['Key', 'Required', 'Values'], keyRows(S, type)), '', 'Keys in this order. Unknown = `—` (never quoted); `version`-like values are quoted.', '');
  const sv = S.raw.statusVocabularies[t.statusVocabulary];
  out.push('## Status', '', `${sv.values.map(code).join(' · ')} — ${sv.meaning} Template: ${code(t.templateStatus)}. ${S.raw.statusVocabularies.rule}`, '');
  out.push('## Sections', '');
  const rows = [];
  if (t.preamble) rows.push(['(text under the title)', t.preamble.required ? 'required' : 'optional', cell(t.preamble.guidance)]);
  for (const s of t.sections) {
    const kind = s.generated ? 'generated' : s.required ? (s.relief ? `required (optional without ${s.relief}/)` : 'required') : s.inTemplate ? 'recommended' : 'optional';
    const g = s.generated ? S.generated[s.heading]?.guidance || s.guidance : s.guidance;
    const extra = s.defaultRelation ? ` Default relation: ${s.defaultRelation}${s.ordered ? ' (ordered 1. 2. …)' : ''}.` : '';
    rows.push([`## ${s.heading}`, kind, cell(g + extra)]);
  }
  out.push(...table(['Section', 'Kind', 'Guidance'], rows), '');
  out.push('Body states: `—` alone = unknown (counted) · `none` alone = verified empty · a final `- —` / `N. —` list item = more items exist but are unknown. Never edit `⚙` sections or the `> ⚙` status line — run `mds regen`.', '');
  if (t.sections.some((s) => s.heading === 'Description & Requirements')) out.push(...presetBlock(S, type));
  const rel = relationRows(S, type);
  if (rel.length) out.push('## Relations written on this type', '', ...table(['Relation', 'Written in', 'Targets', 'Qualifiers', 'Generated reverse'], rel), '');
  for (const [kind, sd] of Object.entries(S.raw.subdocuments)) {
    if (sd.host !== type) continue;
    out.push(`## Sub-document: ${kind}`, '', `Heading ${code(sd.heading)} in ## ${sd.section}${sd.anchor ? `; anchor ${code(sd.anchor.split(' — ')[0])} on the next line` : ''}.`);
    if (sd.passport?.keys?.length) out.push(`Optional passport line: ${sd.passport.keys.map((k) => code(k.key + ':')).join(' · ')} (${sd.passport.order || 'in this order'}).`);
    if (sd.body) out.push(sd.body);
    if (sd.shapes) {
      out.push('', ...table(['Glyph', 'Step', 'Lines', 'Rule'], Object.entries(sd.shapes).map(([n, d]) => [d.glyph, n, cell(Object.entries(d.lines).map(([r, c]) => `${r} ${c}`).join(' · ')), cell(d.rule)])));
      out.push(`Every step may also carry: ${Object.keys(sd.commonLines).join(' · ')} (except where the step's own line replaces it).`);
    }
    for (const r of sd.rules || []) out.push(`- ${r}`);
    out.push('');
  }
  out.push('## Example', '', '```markdown', t.example.replace(/\n$/, ''), '```');
  if (t.exampleSubfeature) out.push('', 'Sub-feature:', '', '```markdown', t.exampleSubfeature.replace(/\n$/, ''), '```');
  return out.join('\n') + '\n';
}

export function linksSheet(S) {
  const g = S.raw.grammar;
  const out = ['# Links and relations', '', GEN_NOTE, '', '## Reference atoms', ''];
  out.push(...table(['Atom', 'Shape', 'Meaning'], [
    ['bound', code('[#<CORE> <Name>](<relative-path>[#<anchor>])'), 'resolves by core; name and path are courtesy — `mds regen` rewrites them'],
    ['hand', code('#<CORE>'), 'valid; `mds regen` upgrades it to bound on relation lines'],
    ['placeholder', code('[~ <Name>]'), 'should exist, does not yet; counted as unresolved'],
    ['unknown', code('—'), 'target unknown (blind spot)'],
  ]), '', 'Never write rendered IDs (`#SC000006V1.0`) in references or front matter.', '');
  out.push('## Line shapes', '');
  for (const [k, v] of Object.entries(g.shapes)) out.push(`- **${k}**: ${code(v)}`);
  out.push('', '## Rules', '', ...S.raw.relationRules.map((r) => `- ${r}`), '');
  out.push('## Sections with a default relation (write lines without a prefix)', '');
  const rows = [];
  for (const type of S.roster) {
    for (const s of S.sections(type)) if (s.defaultRelation && !s.generated) rows.push([type, `## ${s.heading}`, s.defaultRelation, s.ordered ? 'yes' : 'no']);
  }
  out.push(...table(['Type', 'Section', 'Default relation', 'Ordered'], rows), '');
  out.push('## Relation vocabulary', '');
  const rr = [];
  for (const [name, r] of Object.entries(S.relations)) {
    const where = (r.authoredIn || []).map((a) => (a.key ? `${a.type} ${a.key}:` : a.passportKey ? `${a.subdocument} passport ${a.passportKey}:` : a.relation ? `· ${a.qualifier}: on ${a.relation}` : a.subdocument ? `${a.subdocument}${a.shapes ? ' (' + a.shapes.join('/') + ')' : ''}` : `${a.type} ## ${a.section}${a.subsection ? ' › ' + a.subsection : ''}`));
    const targets = r.textSlot ? 'text' : r.targetTypes.length ? r.targetTypes.join(', ') : (r.target || '—');
    const quals = (r.qualifiers || []).map((q) => (q.valueless ? q.key : q.key + (Array.isArray(q.values) ? ': ' + q.values.join('|') : ''))).join(' · ') || '—';
    const gr = r.generatedReverse;
    const rev = r.generatedOnly ? '(generated line)' : gr ? (Array.isArray(gr.section) ? gr.section.join(', ') : gr.section) : '—';
    rr.push([name, cell(where.join('; ') || '—'), cell(targets), cell(quals), cell(rev)]);
  }
  out.push(...table(['Relation', 'Written in', 'Targets', 'Qualifiers', 'Generated reverse'], rr), '');
  const link = S.relations.Link;
  out.push('## External links', '', `${code(link.shape)} — ${link.note}`, '');
  return out.join('\n') + '\n';
}

export function buildKit(S) {
  const written = [];
  const put = (rel, text) => { if (writeIfChanged(path.join(STANDARD_DIR, rel), text)) written.push(rel); };
  for (const type of S.roster) {
    put(toPosix(path.join('templates', `${type}.md`)), renderCard(S, type));
    put(toPosix(path.join('kit', 'skills', 'mdstandard', 'types', `${type}.md`)), typeSheet(S, type));
  }
  put(toPosix(path.join('kit', 'skills', 'mdstandard', 'links.md')), linksSheet(S));
  put(toPosix(path.join('kit', 'skills', 'mdstandard', 'types', '_overview.md')), overviewSheet(S));
  return written;
}
